// =============================================================================
// core/settings.h — persistent device settings and FIDO device secrets (NVS)
// =============================================================================
#pragma once

#include <Arduino.h>

namespace settings {

bool init();

// --- User preferences ---
bool autoApprove();               // Hands-free sign-in and registration (no OK, no PIN)
void setAutoApprove(bool on);
const char* timezone();           // POSIX TZ string for the on-screen clock
void setTimezone(const char* tz);

// --- FIDO device secrets ---
// 32-byte master secret used to derive every credential private key.
// Regenerated by a factory reset, which invalidates all credentials.
const uint8_t* masterKey();
void regenerateMasterKey();

// Global signature counter (monotonic, persisted).
uint32_t nextSignCount();
uint32_t signCount();

// --- On-device PIN (built-in user verification) ---
bool pinIsSet();
int  pinRetries();                 // attempts left before UV is blocked
bool pinSet(const char* pin);      // Validates length / digits; resets retries
bool pinVerify(const char* pin);   // Decrements retries on failure
void pinClear();

// Unlocked session: after the PIN is entered on the device it counts as
// user-verified (like an unlocked phone) until the session expires, the
// device reboots, or `lock` is used. 0 hours = until reboot.
void uvSessionStart();
void uvSessionEnd();
bool uvSessionActive();
uint32_t uvSessionMinutesLeft();   // 0 when locked; UINT32_MAX when "until reboot"
int  uvSessionHours();
void setUvSessionHours(int hours);

// Erase FIDO secrets, PIN and counter (CTAP reset). Keeps WiFi/TOTP/prefs.
void resetFido();

}  // namespace settings
